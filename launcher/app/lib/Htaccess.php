<?php

namespace Wpl;

/**
 * Builds the routing rules that let one WordPress core serve every site.
 *
 * Path mode    example.com/demos/s/<slug>/…     (works on any host)
 * Subdomain    <slug>.demo.example.com/…        (needs wildcard DNS and a
 *              wildcard subdomain whose document root is this folder)
 *
 * For a site, requests are mapped as:
 *   /wp-content/uploads/…   → wpl-uploads/<slug>/…   (its own media)
 *   /_c/<blueprint>/…       → wpl-content/<blueprint>/…  (shared plugins/themes)
 *   /wp-admin/…, /wp-includes/…, /*.php → wpl-core/…
 *   anything else           → wpl-core/index.php (WordPress front controller)
 *
 * WordPress learns which site it is serving from the original REQUEST_URI or
 * host (see app/wp/dispatch.php) — not from rewrite environment variables,
 * which Apache and LiteSpeed pass on differently.
 */
class Htaccess
{
    const MARK_BEGIN = '# BEGIN WP Launcher Lite';
    const MARK_END = '# END WP Launcher Lite';

    public static function rules(): string
    {
        $base = Config::basePath() . '/';
        $slug = WPL_SLUG_RE;
        $out = [
            self::MARK_BEGIN,
            '# Generated by the panel. Change settings there rather than editing this block.',
            'Options -Indexes',
            'DirectoryIndex index.php index.html',
            '<IfModule mod_rewrite.c>',
            'RewriteEngine On',
            'RewriteBase ' . $base,
            '# Pass Authorization headers through to WordPress (REST API, app passwords).',
            'RewriteRule .* - [E=HTTP_AUTHORIZATION:%{HTTP:Authorization}]',
        ];

        if (Config::urlMode() === 'subdomain') {
            // Site rules use root-relative targets: on a site's own host this
            // folder is the document root, whatever path the panel lives at.
            $host = '^(' . $slug . ')\.' . preg_quote((string) Config::get('base_domain'), '/') . '(:[0-9]+)?$';
            $cond = 'RewriteCond %{HTTP_HOST} ' . $host . ' [NC]';
            array_push(
                $out,
                '# Demo sites on their own subdomains',
                $cond,
                'RewriteRule ^wp-admin$ /wp-admin/ [R=301,L]',
                $cond,
                'RewriteRule ^wp-content/uploads/(.*)$ /wpl-uploads/%1/$1 [L]',
                $cond,
                'RewriteRule ^_c/([a-z0-9-]+)/(.*)$ /wpl-content/$1/$2 [L]',
                $cond,
                'RewriteRule ^((wp-admin|wp-includes)/.*)$ /wpl-core/$1 [L]',
                $cond,
                'RewriteRule ^([A-Za-z0-9_-]+\.php)$ /wpl-core/$1 [L]',
                $cond,
                'RewriteCond $1 !^(wpl-core|wpl-uploads|wpl-content)/',
                'RewriteRule ^(.*)$ /wpl-core/index.php [L]'
            );
        } else {
            array_push(
                $out,
                '# Demo sites under /s/<slug>/',
                "RewriteRule ^s/($slug)/wp-admin$ s/$1/wp-admin/ [R=301,L]",
                "RewriteRule ^s/($slug)/wp-content/uploads/(.*)$ wpl-uploads/$1/$2 [L]",
                "RewriteRule ^s/$slug/_c/([a-z0-9-]+)/(.*)$ wpl-content/$1/$2 [L]",
                "RewriteRule ^s/$slug/((wp-admin|wp-includes)/.*)$ wpl-core/$1 [L]",
                "RewriteRule ^s/$slug/([A-Za-z0-9_-]+\.php)$ wpl-core/$1 [L]",
                "RewriteRule ^s/$slug(/.*)?$ wpl-core/index.php [L]"
            );
        }

        array_push(
            $out,
            '# The panel and launcher',
            'RewriteCond %{REQUEST_FILENAME} !-f',
            'RewriteCond %{REQUEST_FILENAME} !-d',
            'RewriteRule ^ index.php [L]',
            '</IfModule>',
            self::MARK_END
        );
        return implode("\n", $out) . "\n";
    }

    /** Write the root .htaccess, keeping anything the host added outside our block. */
    public static function write(): void
    {
        $file = WPL_ROOT . '/.htaccess';
        $existing = is_file($file) ? (string) file_get_contents($file) : '';
        $block = self::rules();
        $pattern = '/' . preg_quote(self::MARK_BEGIN, '/') . '.*?' . preg_quote(self::MARK_END, '/') . '\n?/s';
        if (preg_match($pattern, $existing)) {
            $content = preg_replace($pattern, str_replace('$', '\\$', $block), $existing);
        } else {
            // The shipped pre-install .htaccess is entirely ours; replace it.
            $content = str_contains($existing, '# WP Launcher Lite pre-install') ? $block : $block . "\n" . $existing;
        }
        if (file_put_contents($file, $content) === false) {
            throw new \RuntimeException('Cannot write ' . $file);
        }
        self::writeSubdirRules();
    }

    /** Rules for the runtime folders themselves. */
    public static function writeSubdirRules(): void
    {
        Fs::denyWebAccess(WPL_DATA);

        Fs::ensureDir(WPL_UPLOADS);
        // Uploads are public, but nothing in them may ever run as code.
        file_put_contents(WPL_UPLOADS . '/.htaccess', implode("\n", [
            '# WP Launcher Lite: uploaded media is never executable',
            'Options -Indexes -ExecCGI',
            '<FilesMatch "\.(php[0-9]?|phtml|phar|pht|phps|cgi|pl|py|sh|shtml|asp|aspx|jsp)$">',
            '  <IfModule mod_authz_core.c>',
            '    Require all denied',
            '  </IfModule>',
            '  <IfModule !mod_authz_core.c>',
            '    Order allow,deny',
            '    Deny from all',
            '  </IfModule>',
            '</FilesMatch>',
            '<IfModule mod_php.c>',
            '  php_flag engine off',
            '</IfModule>',
            '<IfModule mod_headers.c>',
            '  Header set X-Robots-Tag "noindex, nofollow"',
            '  Header set X-Content-Type-Options "nosniff"',
            '</IfModule>',
            '',
        ]));

        Fs::ensureDir(WPL_CONTENT);
        file_put_contents(WPL_CONTENT . '/.htaccess', implode("\n", [
            '# WP Launcher Lite: shared plugins and themes',
            'Options -Indexes',
            '<IfModule mod_headers.c>',
            '  Header set X-Robots-Tag "noindex, nofollow"',
            '</IfModule>',
            '',
        ]));

        Fs::ensureDir(WPL_CORE);
        // Stops a second rewrite pass inside the core, and — being read-only —
        // stops WordPress writing its own permalink rules here.
        $core = WPL_CORE . '/.htaccess';
        @chmod($core, 0644);
        file_put_contents($core, implode("\n", [
            '# WP Launcher Lite: shared WordPress core. Requests arrive here already routed.',
            'Options -Indexes',
            '<IfModule mod_rewrite.c>',
            'RewriteEngine Off',
            '</IfModule>',
            '<IfModule mod_headers.c>',
            '  Header set X-Robots-Tag "noindex, nofollow"',
            '</IfModule>',
            '',
        ]));
        @chmod($core, 0444);
    }
}
